"""Extract existing station names/positions from OSM nodes and station footprints.

Usage: python scripts/build-shanghai-station-names.py SHANGHAI.osm.pbf [JIANGSU.osm.pbf]
Requires osmium. Coordinates use the game's existing WGS-84 projection.
Construction, proposed, disused and abandoned stations are excluded.
"""
import json
from pathlib import Path
import re
import sys
import osmium

ROOT = Path(__file__).resolve().parent.parent
PROJ = json.loads(re.search(r'proj:\s*(\{[^}]+\})', (ROOT / 'js/geo_sh.js').read_text()).group(1))
PENDING = re.compile(r'在建|规划|建设中|预留|拟建|停用|废弃|construction|proposed|planned|disused|abandoned', re.I)


class Stations(osmium.SimpleHandler):
    def __init__(self):
        super().__init__()
        self.rows = {}

    def name(self, tags):
        if tags.get('railway') != 'station':
            return None
        if tags.get('landuse') == 'construction' or any(tags.get(k) in ('yes', 'station') for k in ('construction', 'proposed', 'disused', 'abandoned')):
            return None
        if any(tag.k.startswith(('construction:', 'proposed:', 'disused:', 'abandoned:')) for tag in tags):
            return None
        name = tags.get('name:zh-Hans') or tags.get('name:zh') or tags.get('name')
        return name if name and not PENDING.search(name) else None

    def add(self, name, lon, lat, tags):
        x, y = (lon - PROJ['lon0']) * PROJ['kx'], (PROJ['lat0'] - lat) * PROJ['ky']
        if not (0 <= x < 512 and 0 <= y < 560):
            return
        kind = 0 if tags.get('station') == 'subway' or tags.get('subway') == 'yes' else 1
        row = [name, round(x, 2), round(y, 2), kind]
        self.rows[(name, round(x * 2), round(y * 2), kind)] = row

    def node(self, n):
        name = self.name(n.tags)
        if name and n.location.valid():
            self.add(name, n.lon, n.lat, n.tags)

    def way(self, w):
        name = self.name(w.tags)
        if not name:
            return
        pts = [(n.lon, n.lat) for n in w.nodes if n.location.valid()]
        if not pts:
            return
        # Midpoint of the station footprint; naming radius is 800 m.
        self.add(name, (min(p[0] for p in pts) + max(p[0] for p in pts)) / 2,
                 (min(p[1] for p in pts) + max(p[1] for p in pts)) / 2, w.tags)


if __name__ == '__main__':
    h = Stations()
    for source in sys.argv[1:]:
        h.apply_file(source, locations=True, idx='flex_mem')
    if not h.rows:
        raise SystemExit('No stations extracted; supply an OSM PBF file.')
    rows = sorted(h.rows.values(), key=lambda r: (r[3], r[0], r[1], r[2]))
    target = ROOT / 'js/data_sh_station_names.js'
    target.write_text("'use strict';\n// Existing OSM station nodes and footprints; OpenStreetMap contributors, ODbL.\n"
                      "// Generated by scripts/build-shanghai-station-names.py; not player-built lines.\n"
                      "(function(CM){CM.SH_STATION_NAMES=" + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ";})(window.CM);\n")
    print(json.dumps({'stations': len(rows), 'output': str(target)}, ensure_ascii=False))
